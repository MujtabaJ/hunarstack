export function collectPhotos(site) {
  const rows = [];
  if (site.hero?.image) rows.push({ key: "hero.image", label: "Hero photo", src: site.hero.image, alt: site.hero.imageAlt || "" });
  (site.sections || []).forEach((s) => {
    if (s.image) rows.push({ key: `section:${s.id}:image`, label: `${s.title || s.id} photo`, src: s.image, alt: s.imageAlt || "" });
    (s.items || []).forEach((item) => {
      if (item.image) rows.push({ key: `item:${s.id}:${item.id}:image`, label: `${s.id} / ${item.title || item.id}`, src: item.image, alt: item.imageAlt || "" });
    });
  });
  return rows;
}
